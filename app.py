def validate_payload(p: dict) -> list:
    """Client-side checks before calling the API. Returns a list of messages."""
    errors = []
    if not 10 <= p["age"] <= 100:
        errors.append("Age must be between 10 and 100.")
    for key, label in [
        ("avg_daily_usage_hours", "Average daily usage hours"),
        ("study_hours", "Study hours"),
        ("physical_activity_hours", "Physical activity hours"),
        ("sleep_hours_per_night", "Sleep hours per night"),
    ]:
        if not 0 <= p[key] <= 24:
            errors.append(f"{label} must be between 0 and 24.")
    if p["daily_unlocks"] < 0:
        errors.append("Daily unlocks cannot be negative.")
    day_total = p["study_hours"] + p["physical_activity_hours"] + p["sleep_hours_per_night"]
    if day_total > 24:
        errors.append(
            f"Study, physical activity and sleep add up to {day_total:.1f} hours, "
            "which is more than a day has. Please adjust them."
        )
    return errors


def call_api(payload: dict) -> dict:
    """
    POST the payload to FastAPI. Returns either
      {"ok": True, "score": float}
    or
      {"ok": False, "level": "error"|"warning", "title": str, "detail": str}
    A prediction is never fabricated on failure.
    """
    def fail(title, detail, level="error"):
        return {"ok": False, "level": level, "title": title, "detail": detail}

    try:
        response = requests.post(API_URL, json=payload, timeout=API_TIMEOUT)
    except requests.exceptions.ConnectionError:
        return fail("Backend not reachable",
                    f"Could not connect to {API_URL}. Start the FastAPI server with "
                    "`uvicorn main:app --reload` and try again.")
    except requests.exceptions.Timeout:
        return fail("Request timed out",
                    f"The backend did not respond within {API_TIMEOUT} seconds. "
                    "Please try again.", "warning")
    except requests.exceptions.RequestException as exc:
        return fail("Request failed", f"Unexpected network error: {exc}")

    if response.status_code == 422:
        detail = "The backend rejected the input data."
        try:
            items = response.json().get("detail", [])
            if isinstance(items, list):
                parts = [f"{'.'.join(str(x) for x in i.get('loc', []))}: {i.get('msg', '')}"
                         for i in items if isinstance(i, dict)]
                if parts:
                    detail += " " + "; ".join(parts)
        except ValueError:
            pass
        return fail("Validation error (422)", detail, "warning")

    if response.status_code >= 500:
        return fail(f"Server error ({response.status_code})",
                    "The backend hit an internal error. Check the FastAPI terminal for details.")

    if response.status_code != 200:
        return fail(f"Unexpected response ({response.status_code})", response.text[:300])

    try:
        data = response.json()
    except ValueError:
        return fail("Invalid response", "The backend did not return valid JSON.")

    if not isinstance(data, dict) or "predicted_mental_health_score" not in data:
        return fail("Missing field in response",
                    "The response did not contain 'predicted_mental_health_score'.")

    try:
        score = float(data["predicted_mental_health_score"])
    except (TypeError, ValueError):
        return fail("Invalid score", "The returned score is not a number.")

    if not math.isfinite(score):
        return fail("Invalid score", "The returned score is not a finite number.")

    return {"ok": True, "score": score}


def build_gauge(score: float) -> go.Figure:
    """Neutral circular-style gauge: no categories, no good/bad colour bands."""
    low = min(0.0, math.floor(score))
    high = max(100.0, math.ceil(score))
    fig = go.Figure(go.Indicator(
        mode="gauge+number",
        value=score,
        number={"valueformat": ".2f", "font": {"size": 56, "color": "#4c1d95"}},
        gauge={
            "axis": {"range": [low, high], "tickcolor": "#a78bfa"},
            "bar": {"color": "#7c3aed", "thickness": 0.3},
            "bgcolor": "#ede9fe",
            "borderwidth": 0,
        },
    ))
    fig.update_layout(height=340, margin=dict(l=30, r=30, t=30, b=10),
                      paper_bgcolor="rgba(0,0,0,0)",
                      font={"family": "Plus Jakarta Sans, sans-serif"})
    return fig


